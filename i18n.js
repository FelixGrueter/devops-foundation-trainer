  const pick = (l, key) => (I18N[l] && I18N[l][key] !== undefined) ? I18N[l][key] : I18N.de[key];
  /* t(key, vars?, forceLang?) – vars.n wählt bei vorhandenen _one/_other-Varianten die Pluralform */
  function t(key, vars, forceLang){
    const l = forceLang || lang;
    let s;
    if(vars && typeof vars.n === 'number') s = pick(l, key + (vars.n === 1 ? '_one' : '_other'));
    if(s === undefined) s = pick(l, key);
    if(s === undefined) return key;                                   // unbekannter Schlüssel: sichtbar statt leer
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars) ? vars[k] : m) : s;
  }
